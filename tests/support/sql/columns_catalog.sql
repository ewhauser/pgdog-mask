-- Columns of every relation, from pg_attribute. Unlike information_schema.columns,
-- this isn't filtered by the privileges of the loading role. data_type follows
-- information_schema's definition so callers see the same values.
SELECT
    current_database()::text AS table_catalog,
    n.nspname::text AS table_schema,
    c.relname::text AS table_name,
    a.attname::text AS column_name,
    COALESCE(
        CASE WHEN a.attgenerated = '' THEN pg_catalog.pg_get_expr(d.adbin, d.adrelid) END,
        CASE a.attidentity
            WHEN 'a' THEN 'generated always as identity'
            WHEN 'd' THEN 'generated by default as identity'
        END
    )::text AS column_default,
    (NOT a.attnotnull)::text AS is_nullable,
    (CASE
        WHEN t.typtype = 'd' THEN
            CASE
                WHEN bt.typelem <> 0 AND bt.typlen = -1 THEN 'ARRAY'
                WHEN nbt.nspname = 'pg_catalog' THEN pg_catalog.format_type(t.typbasetype, NULL)
                ELSE 'USER-DEFINED'
            END
        ELSE
            CASE
                WHEN t.typelem <> 0 AND t.typlen = -1 THEN 'ARRAY'
                WHEN nt.nspname = 'pg_catalog' THEN pg_catalog.format_type(a.atttypid, NULL)
                ELSE 'USER-DEFINED'
            END
    END)::text AS data_type,
    a.attnum::int AS ordinal_position,
    EXISTS (
        SELECT 1
        FROM pg_catalog.pg_constraint con
        WHERE con.conrelid = c.oid
            AND con.contype = 'p'
            AND a.attnum = ANY (con.conkey)
    )::text AS is_primary_key,
    pg_catalog.format_type(a.atttypid, NULL)::text AS type_name,
    pg_catalog.col_description(c.oid, a.attnum)::text AS comment,
    COALESCE((
        SELECT pg_catalog.json_agg(
            pg_catalog.json_build_object('provider', l.provider, 'label', l.label)
            ORDER BY l.provider
        )
        FROM pg_catalog.pg_seclabel l
        WHERE l.classoid = 'pg_catalog.pg_class'::pg_catalog.regclass
            AND l.objoid = c.oid
            AND l.objsubid = a.attnum
    ), '[]')::text AS security_labels,
    -- RowDescription reports the base type of domains.
    (CASE WHEN t.typtype = 'd' THEN t.typbasetype ELSE a.atttypid END)::bigint::text AS type_oid
FROM
    pg_catalog.pg_class c
JOIN
    pg_catalog.pg_namespace n ON n.oid = c.relnamespace
JOIN
    pg_catalog.pg_attribute a ON a.attrelid = c.oid
JOIN
    pg_catalog.pg_type t ON t.oid = a.atttypid
JOIN
    pg_catalog.pg_namespace nt ON nt.oid = t.typnamespace
LEFT JOIN
    pg_catalog.pg_type bt ON t.typtype = 'd' AND bt.oid = t.typbasetype
LEFT JOIN
    pg_catalog.pg_namespace nbt ON nbt.oid = bt.typnamespace
LEFT JOIN
    pg_catalog.pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
WHERE
    c.relkind IN ('r', 'p', 'v', 'm', 'f')
    AND a.attnum > 0
    AND NOT a.attisdropped
    AND n.nspname NOT IN ('pg_catalog', 'information_schema')
    AND n.nspname !~ '^pg_toast'
ORDER BY
    table_schema, table_name, ordinal_position
